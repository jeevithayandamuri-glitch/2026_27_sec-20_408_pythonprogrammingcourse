#Implement a Python program to demonstrate set creation and basic set operations (union, intersection, difference)
set_a={1,2,3,4}
set_b={3,4,5,6}
print("seta:",set_a)
print("setb:",set_b)
print("union:",set_a|set_b)
print("intersection:",set_a&set_b)
print("difference:",set_a - set_b)
print("difference:",set_b - set_a)