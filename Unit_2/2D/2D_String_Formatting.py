#Implement a Python program to demonstrate string formatting (format(), f-strings, % operator)
name="jeevitha"
age=50

print("my name is {} and i am {} years old.".format(name,age))
print(f"my name is {name} and age is {age} years old.")
print(f"my name is %s and i am %s years old."% (name,age))
